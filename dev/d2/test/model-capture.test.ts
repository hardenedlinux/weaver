import {test,expect} from 'bun:test';
import {createHash} from 'node:crypto';
import fc from 'fast-check';
import {readModelCapture} from '../src/source/models';
const hash=(value:string)=>createHash('sha256').update(value).digest('hex');
test('property: image jobs accept only the Go-owned capture and exact source cohort',()=>{
 fc.assert(fc.property(fc.array(fc.string({maxLength:80}),{minLength:1,maxLength:8}),texts=>{
  const documents=Object.fromEntries(texts.map((text,index)=>['models/m'+index+'.sysml',text]));
  const raw=JSON.stringify({modelHash:'sdk-model',sources:Object.fromEntries(Object.entries(documents).map(([name,text])=>[name,hash(text)])),views:{view:{}}});
  const digest=hash(raw),capture=readModelCapture(raw,digest,documents);
  expect(capture.modelHash).toBe('sdk-model');
  expect(capture.sha256).toBe(digest);
  expect(()=>readModelCapture(raw+' ',digest,documents)).toThrow('Go owner receipt');
  expect(()=>readModelCapture(raw,digest,{...documents,'models/m0.sysml':texts[0]+';'})).toThrow('SDK source changed');
  expect(()=>readModelCapture(raw,digest,{...documents,'models/new.sysml':'package New {}'})).toThrow('cohort differs');
 }),{numRuns:100,seed:293});
});
test('malformed capture metadata cannot stand in for an SDK result',()=>{
 for(const value of [[],null,{}, {modelHash:'',sources:{},views:{}},{modelHash:'m',sources:{},views:[]}]){
  const raw=JSON.stringify(value);
  expect(()=>readModelCapture(raw,hash(raw),{})).toThrow('Invalid SDK capture envelope');
 }
});

test('derived D2 and Lean references cannot become independent design inputs',()=>{
 const documents={'Project.sysml':'package Example {}','docs/view.d2':'derived declaration','dev/proofs/lean/Proof.lean':'theorem retained : True := True.intro'};
 const raw=JSON.stringify({modelHash:'sdk-model',sources:{'Project.sysml':hash(documents['Project.sysml'])},views:{view:{}},mapped:{'docs/view.d2':documents['docs/view.d2']},proofSources:{'dev/proofs/lean/Proof.lean':documents['dev/proofs/lean/Proof.lean']}});
 expect(readModelCapture(raw,hash(raw),documents).proofSources['dev/proofs/lean/Proof.lean']).toBe(documents['dev/proofs/lean/Proof.lean']);
 expect(()=>readModelCapture(raw,hash(raw),{...documents,'docs/view.d2':'manual semantic replacement'})).toThrow('Derived D2 differs');
 expect(()=>readModelCapture(raw,hash(raw),{...documents,'dev/proofs/lean/Proof.lean':'changed theorem'})).toThrow('Lean source changed');
});

test('selected render scope cannot masquerade as a complete mapped inventory',()=>{
 const marker='# Generated by Go from SysML and Lean references.';
 const documents={'Project.sysml':'package Example {}','docs/one.d2':marker,'docs/two.d2':marker};
 const raw=JSON.stringify({modelHash:'sdk-model',sources:{'Project.sysml':hash(documents['Project.sysml'])},views:{},mapped:{'docs/one.d2':marker}});
 expect(readModelCapture(raw,hash(raw),documents,['docs/one.d2']).mapped['docs/one.d2']).toBe(marker);
 expect(()=>readModelCapture(raw,hash(raw),documents)).toThrow('Missing authoritative mapped source');
 for(const selection of [[],['docs/two.d2'],['docs/one.d2','docs/one.d2']])expect(()=>readModelCapture(raw,hash(raw),documents,selection)).toThrow('Selected scope');
});
