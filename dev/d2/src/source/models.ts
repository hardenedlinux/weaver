import {createHash} from 'node:crypto';
import {renderedViewFromJson} from '@openmbee/opensysml';
import type {OpenSysMLCapture} from '@deterministic-engineering/render/opensysml';
export interface ModelCapture {
 readonly modelHash:string;
 readonly sources:Readonly<Record<string,string>>;
 readonly views:Readonly<Record<string,unknown>>;
 readonly sha256:string;
 readonly proofSources:Readonly<Record<string,string>>;
 readonly mapped:Readonly<Record<string,string>>;
}
const object=(value:unknown):value is Record<string,unknown>=>Boolean(value)&&typeof value==='object'&&!Array.isArray(value);
const hash=(value:string)=>createHash('sha256').update(value).digest('hex');

/** Transport/cohort validation only. The Library owns SDK model interpretation. */
export function readModelCapture(raw:string,expected:string,documents:Readonly<Record<string,string>>,selection?:readonly string[]):ModelCapture {
 if(!/^[a-f0-9]{64}$/.test(expected)||hash(raw)!==expected)throw new Error('SDK capture differs from the Go owner receipt');
 const value:unknown=JSON.parse(raw);
 if(!object(value)||typeof value.modelHash!=='string'||!value.modelHash.trim()||!object(value.sources)||!object(value.views))throw new Error('Invalid SDK capture envelope');
 const modelSources=Object.entries(documents).filter(([name])=>name.endsWith('.sysml'));
 const sources:Record<string,string>={};
 if(Object.keys(value.sources).length!==modelSources.length)throw new Error('SDK source cohort differs');
 for(const [name,text]of modelSources){const digest=value.sources[name];if(typeof digest!=='string'||digest!==hash(text))throw new Error('SDK source changed: '+name);sources[name]=digest;}
 const proofSources:Record<string,string>={};
 if(value.proofSources!==undefined){
  if(!object(value.proofSources))throw new Error('Invalid proof source capture');
  for(const [name,text]of Object.entries(value.proofSources)){if(typeof text!=='string'||documents[name]!==text)throw new Error('Lean source changed: '+name);proofSources[name]=text;}
 }
 if(value.mapped!==undefined){
  if(!object(value.mapped))throw new Error('Invalid mapped view capture');
  for(const [name,text]of Object.entries(value.mapped)){if(typeof text!=='string'||documents[name]!==text)throw new Error('Derived D2 differs from SysML/Lean mapping: '+name);}
 }
 const mapped:Record<string,string>={};
 if(object(value.mapped))for(const[name,text]of Object.entries(value.mapped)){
  if(typeof text!=='string')throw new Error('Invalid mapped source');
  mapped[name]=text;
 }
 if(selection && (selection.length===0||new Set(selection).size!==selection.length||selection.some(name=>!Object.hasOwn(mapped,name))))throw new Error('Selected scope lacks authoritative mapped sources');
 for(const[name,text]of Object.entries(documents))if((!selection||selection.includes(name))&&name.endsWith('.d2')&&text.includes('# Generated by Go from SysML and Lean references.')&&!Object.hasOwn(mapped,name))throw new Error('Missing authoritative mapped source: '+name);
 return {modelHash:value.modelHash,sources,views:value.views,sha256:expected,proofSources,mapped};
}

/** SDK transport decoding only; model interpretation and projection belong to Library. */
export function capturedViews(capture:ModelCapture|undefined):Readonly<Record<string,OpenSysMLCapture>> {
 return Object.fromEntries(Object.entries(capture?.views??{}).map(([view,raw])=>[view,{modelHash:capture!.modelHash,requestedView:view,rendering:renderedViewFromJson(raw)}]));
}
